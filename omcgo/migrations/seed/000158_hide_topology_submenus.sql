-- 隐藏拓扑管理下三个子菜单：拓扑图、域管理、站点管理
-- ============================================================
--
-- 前端 navConfig.ts 已隐藏这三个菜单项，后端同步修改 show_status 为 'hide'：
--   - 拓扑图 (topology:canvas) - aaaa0004-1000-0000-0000-000000000001
--   - 域管理 (topology:domain)   - aaaa0004-1000-0002-0000-000000000001
--   - 站点管理 (topology:site)    - aaaa0004-1000-0003-0000-000000000001
--
-- 保留显示：
--   - GIS地图 (topology:gis-map)  - aaaa0004-1000-0001-0000-000000000001
--
-- 注意：只隐藏菜单，不删除数据，方便后续需要时恢复
-- ============================================================

UPDATE menus
SET show_status = 'hide', updated_at = NOW()
WHERE id IN (
  'aaaa0004-1000-0000-0000-000000000001',  -- 拓扑图
  'aaaa0004-1000-0002-0000-000000000001',  -- 域管理
  'aaaa0004-1000-0003-0000-000000000001'   -- 站点管理
);

