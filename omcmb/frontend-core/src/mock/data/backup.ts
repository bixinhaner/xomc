export interface BackupTask {
  id: string;
  taskName: string;
  taskType: 'manual' | 'scheduled';
  deviceSns: string[];
  status: 'pending' | 'running' | 'success' | 'failed' | 'cancelled';
  progress: number;
  successCount: number;
  failCount: number;
  totalCount: number;
  backupType: 'full' | 'incremental' | 'config-only';
  storageLocation: string;
  fileSize?: number;
  createdAt: string;
  updatedAt: string;
  creator: string;
  message?: string;
}

export interface BackupSchedule {
  id: string;
  scheduleName: string;
  deviceGroups: string[];
  backupType: 'full' | 'incremental' | 'config-only';
  cronExpression: string;
  cronDescription: string;
  enabled: boolean;
  retentionDays: number;
  storageLocation: string;
  lastRunTime?: string;
  nextRunTime: string;
  createTime: string;
  creator: string;
}

export interface FTPConfig {
  id: string;
  configName: string;
  host: string;
  port: number;
  username: string;
  protocol: 'FTP' | 'SFTP' | 'FTPS';
  remotePath: string;
  passive: boolean;
  enabled: boolean;
  createTime: string;
}

